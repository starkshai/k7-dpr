// ============================================================================
// spi_flash_reader.v
// AXI4 read slave that bridges the PRC m_axi_mem interface to SPI Flash.
// CCLK is driven through STARTUPE2 (in top.v). Data pins are regular I/O.
// Protocol: Standard SPI Read (0x03), Mode 0 (CPOL=0, CPHA=0)
//
// WORD FORMAT: the partial .bin is stored in the flash as a stream of
// little-endian 32-bit words (write_cfgmem SMAPx32 output). The PRC applies
// its own per-byte bit-reverse (rev8, byte lanes preserved) to turn each AXI
// rdata word into the bit-swapped SelectMAP format ICAPE2.I expects. So the
// reader must deliver the file word verbatim: rdata = {B3, B2, B1, B0} with
// B0 the first byte read from the flash. Any extra bit-reverse here cancels
// the PRC's swap, the ICAP then sees the un-swapped sync word 0xAA995566
// instead of 0x5599AA66, never aligns (O[7:4]=0x9, DALIGN=0) and silently
// ignores the whole stream while the PRC still reports FULL/error=0.
//
// SCLK is generated by dividing the 100 MHz system clock. Because CCLK is
// routed out through the STARTUPE2 startup block (USRCCLKO) and MISO returns
// through a normal I/O, the round-trip delay is large and uncontrolled. A
// 50 MHz SCLK left almost no sampling margin and produced sporadic bit errors
// over a full ~3.9 Mbit partial bitstream; the ICAP rejected the result on its
// internal CRC check while the PRC (which does not observe that CRC) still
// reported FULL/rm_id/error=0 and the fabric was never reprogrammed. SCLK_DIV
// system clocks per SCLK half-period give a 12.5 MHz SCLK and sample MISO
// ~40 ns after the rising edge, covering the startup round-trip. Load time
// rises to ~310 ms, acceptable for a button-triggered reconfiguration.
// ============================================================================

module spi_flash_reader (
    input  wire        clk,
    input  wire        rst,

    input  wire [31:0] s_axi_araddr,
    input  wire [7:0]  s_axi_arlen,
    input  wire [2:0]  s_axi_arsize,
    input  wire [1:0]  s_axi_arburst,
    input  wire [3:0]  s_axi_arcache,
    input  wire [2:0]  s_axi_arprot,
    input  wire        s_axi_arvalid,
    output wire        s_axi_arready,

    output wire [31:0] s_axi_rdata,
    output wire [1:0]  s_axi_rresp,
    output wire        s_axi_rlast,
    output wire        s_axi_rvalid,
    input  wire        s_axi_rready,

    output wire        spi_clk_o,
    output wire        spi_clk_ts,
    output wire        spi_ce_b,
    output wire        spi_d0_o,
    input  wire        spi_d1_i,

    output wire [3:0]  dbg_state,
    output wire [3:0]  dbg_seq
);

    localparam CMD_STANDARD_READ = 8'h03;

    // System clocks per SCLK half-period. SCLK = 100 MHz / (2 * SCLK_DIV).
    // SCLK_DIV = 4 -> 12.5 MHz (safe through the STARTUPE2 CCLK round-trip).
    localparam integer SCLK_DIV = 4;

    localparam ST_IDLE       = 4'd0;
    localparam ST_CMD_SETUP  = 4'd1;
    localparam ST_CMD        = 4'd2;
    localparam ST_ADDR_SETUP = 4'd3;
    localparam ST_ADDR       = 4'd4;
    localparam ST_DATA_SETUP = 4'd5;
    localparam ST_DATA       = 4'd6;
    localparam ST_DONE       = 4'd7;

    reg [3:0]  state;
    reg [3:0]  seq;
    reg [2:0]  pclk;
    reg [7:0]  shift_out;
    reg [7:0]  shift_in;
    reg [31:0] burst_addr;
    reg [7:0]  beats_left;
    reg [2:0]  addr_byte_idx;
    reg [1:0]  data_byte_idx;
    reg [31:0] rx_data;
    reg        ar_accepted;
    reg [31:0] axi_rdata_r;
    reg        axi_rvalid_r;
    reg        axi_rlast_r;
    reg        axi_arready_r;

    wire spi_active = (state == ST_CMD || state == ST_ADDR || state == ST_DATA);

    assign spi_clk_o   = spi_active ? seq[0] : 1'b0;
    assign spi_clk_ts  = 1'b0;
    assign spi_d0_o    = shift_out[7];
    assign spi_ce_b    = (state == ST_IDLE || state == ST_DONE) ? 1'b1 : 1'b0;

    assign dbg_state   = state;
    assign dbg_seq     = seq;

    assign s_axi_arready = axi_arready_r;
    assign s_axi_rdata   = axi_rdata_r;
    assign s_axi_rvalid  = axi_rvalid_r;
    assign s_axi_rlast   = axi_rlast_r;
    assign s_axi_rresp   = 2'b00;

    wire byte_done    = (seq == 4'd15);
    wire setup_phase  = (seq[0] == 1'b0);
    wire sample_phase = (seq[0] == 1'b1);
    wire [7:0] miso_byte = {shift_in[6:0], spi_d1_i};
    wire spi_paused = axi_rvalid_r & ~s_axi_rready;
    // Advance the SPI engine once every SCLK_DIV system clocks.
    wire spi_tick   = (pclk == (SCLK_DIV - 1));

    always @(posedge clk) begin
        if (rst) begin
            state          <= ST_IDLE;
            seq            <= 4'd0;
            pclk           <= 3'd0;
            shift_out      <= 8'd0;
            shift_in       <= 8'd0;
            burst_addr     <= 32'd0;
            beats_left     <= 8'd0;
            addr_byte_idx  <= 3'd0;
            data_byte_idx  <= 2'd0;
            rx_data        <= 32'd0;
            ar_accepted    <= 1'b0;
            axi_arready_r  <= 1'b0;
            axi_rdata_r    <= 32'd0;
            axi_rvalid_r   <= 1'b0;
            axi_rlast_r    <= 1'b0;
        end else begin

            if (axi_rvalid_r && s_axi_rready) begin
                axi_rvalid_r <= 1'b0;
                axi_rlast_r  <= 1'b0;
            end

            case (state)
                ST_IDLE: begin
                    seq           <= 4'd0;
                    pclk          <= 3'd0;
                    axi_arready_r <= 1'b0;
                    if (s_axi_arvalid && !ar_accepted) begin
                        ar_accepted   <= 1'b1;
                        axi_arready_r <= 1'b1;
                        burst_addr    <= s_axi_araddr;
                        beats_left    <= s_axi_arlen;
                        shift_out     <= CMD_STANDARD_READ;
                        addr_byte_idx <= 3'd0;
                        data_byte_idx <= 2'd0;
                        rx_data       <= 32'd0;
                        state         <= ST_CMD_SETUP;
                    end
                end

                ST_CMD_SETUP: begin
                    seq           <= 4'd0;
                    pclk          <= 3'd0;
                    shift_out     <= CMD_STANDARD_READ;
                    axi_arready_r <= 1'b0;
                    state         <= ST_CMD;
                end

                ST_CMD: begin
                    if (!spi_paused) begin
                        if (!spi_tick) begin
                            pclk <= pclk + 3'd1;
                        end else begin
                            pclk <= 3'd0;
                            if (seq == 4'd0) begin
                                seq <= 4'd1;
                            end else begin
                                seq <= seq + 1;
                            end
                            if (sample_phase) begin
                                shift_out <= {shift_out[6:0], 1'b0};
                                shift_in  <= {shift_in[6:0], spi_d1_i};
                                if (byte_done) begin
                                    seq       <= 4'd0;
                                    shift_out <= burst_addr[23:16];
                                    state     <= ST_ADDR_SETUP;
                                end
                            end
                        end
                    end
                end

                ST_ADDR_SETUP: begin
                    seq  <= 4'd0;
                    pclk <= 3'd0;
                    case (addr_byte_idx)
                        3'd0: shift_out <= burst_addr[23:16];
                        3'd1: shift_out <= burst_addr[15:8];
                        3'd2: shift_out <= burst_addr[7:0];
                    endcase
                    state <= ST_ADDR;
                end

                ST_ADDR: begin
                    if (!spi_paused) begin
                        if (!spi_tick) begin
                            pclk <= pclk + 3'd1;
                        end else begin
                            pclk <= 3'd0;
                            if (seq == 4'd0) begin
                                seq <= 4'd1;
                            end else begin
                                seq <= seq + 1;
                            end
                            if (sample_phase) begin
                                shift_out <= {shift_out[6:0], 1'b0};
                                shift_in  <= {shift_in[6:0], spi_d1_i};
                                if (byte_done) begin
                                    seq <= 4'd0;
                                    if (addr_byte_idx == 3'd2) begin
                                        shift_out     <= 8'h00;
                                        data_byte_idx <= 2'd0;
                                        rx_data       <= 32'd0;
                                        state         <= ST_DATA_SETUP;
                                    end else begin
                                        addr_byte_idx <= addr_byte_idx + 1;
                                        case (addr_byte_idx + 1)
                                            3'd1: shift_out <= burst_addr[15:8];
                                            3'd2: shift_out <= burst_addr[7:0];
                                        endcase
                                    end
                                end
                            end
                        end
                    end
                end

                ST_DATA_SETUP: begin
                    seq       <= 4'd0;
                    pclk      <= 3'd0;
                    shift_out <= 8'h00;
                    state     <= ST_DATA;
                end

                ST_DATA: begin
                    if (!spi_paused) begin
                        if (!spi_tick) begin
                            pclk <= pclk + 3'd1;
                        end else begin
                            pclk <= 3'd0;
                            if (seq == 4'd0) begin
                                seq <= 4'd1;
                            end else begin
                                seq <= seq + 1;
                            end
                            if (setup_phase)
                                shift_out <= 8'h00;
                            if (sample_phase) begin
                                shift_in  <= {shift_in[6:0], spi_d1_i};
                                shift_out <= {shift_out[6:0], 1'b0};
                                if (byte_done) begin
                                    seq <= 4'd0;
                                    case (data_byte_idx)
                                        2'd0: rx_data[31:24] <= miso_byte;
                                        2'd1: rx_data[23:16] <= miso_byte;
                                        2'd2: rx_data[15:8]  <= miso_byte;
                                        2'd3: begin
                                            axi_rdata_r  <= {miso_byte, rx_data[15:8],
                                                             rx_data[23:16], rx_data[31:24]};
                                            axi_rvalid_r <= 1'b1;
                                            axi_rlast_r  <= (beats_left == 8'd0);
                                            if (beats_left == 8'd0)
                                                state <= ST_DONE;
                                            else
                                                beats_left <= beats_left - 1;
                                        end
                                    endcase
                                    if (data_byte_idx != 2'd3)
                                        data_byte_idx <= data_byte_idx + 1;
                                    else
                                        data_byte_idx <= 2'd0;
                                end
                            end
                        end
                    end
                end

                ST_DONE: begin
                    seq  <= 4'd0;
                    pclk <= 3'd0;
                    if (!axi_rvalid_r) begin
                        ar_accepted   <= 1'b0;
                        axi_arready_r <= 1'b0;
                        state         <= ST_IDLE;
                    end
                end

                default: state <= ST_IDLE;
            endcase
        end
    end

endmodule
